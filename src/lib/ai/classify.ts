// Word-boundary keyword match. Substring matching was catching false positives
// on short keywords (e.g. "ai" matching "wait", "main", "available"). Word
// boundaries fix that for all keywords with negligible perf cost at our scale.
function kwMatches(text: string, kw: string): boolean {
  const escaped = kw.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`\\b${escaped}\\b`, "i").test(text);
}

function extractKeywords(title: string, content: string): string {
  return `${title} ${content}`.toLowerCase();
}

export function classifyArticle(title: string, content: string): string[] {
  const text = extractKeywords(title, content);
  const matched: string[] = [];

  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    if (keywords.some((kw) => kwMatches(text, kw))) {
      matched.push(category);
    }
  }

  return [...new Set(matched)];
}

export function getPrimaryCategory(
  title: string,
  content: string,
  source: string
): string {
  const keywords = classifyArticle(title, content);
  const sourceHint = SOURCE_CATEGORY_HINTS[source];

  if (keywords.length === 0 && sourceHint) {
    return sourceHint[0];
  }

  // If keywords matched, pick the most specific single category.
  // Priority chain: world > us > business > tech > science > sports > culture
  // Geopolitics wins over domestic; business beats tech when both match
  // (a "Tesla earnings" story is business, not tech).
  if (keywords.length > 0) {
    const priority = ["world", "us", "business", "tech", "science", "sports", "culture"];
    for (const cat of priority) {
      if (keywords.includes(cat)) return cat;
    }
  }

  if (sourceHint) return sourceHint[0];

  return "world";
}

